    def _segment_text(self, text: str) -> List[str]:
        """
        Segment text into sentences with better handling of Indian language punctuation
        """
        text = re.sub(r'\s+', ' ', text).strip()
        
        if self.lang_code == 'te':
            # Handle Telugu punctuation (including both Devanagari and Latin marks)
            sentences = re.split(r'(?<=[.!?।॥])\s+', text)
        elif self.lang_code == 'hi':
            # Handle Hindi punctuation
            sentences = re.split(r'(?<=[.!?।॥])\s+', text)
        else:
            # Default sentence segmentation
            sentences = re.split(r'(?<=[.!?])\s+', text)
        
        # Clean up sentences
        clean_sentences = []
        for sentence in sentences:
            sentence = sentence.strip()
            if sentence and len(sentence.split()) >= 2:  # Require at least 2 words
                # Ensure sentences end with proper punctuation
                if not sentence[-1] in '.!?।॥':
                    if self.lang_code == 'te':
                        sentence += '.'
                    elif self.lang_code == 'hi':
                        sentence += '।'
                    else:
                        sentence += '.'
                clean_sentences.append(sentence)
        
        return clean_sentences
    
    def _score_sentences(self, sentences: List[str]) -> Dict[int, float]:
        """
        Score sentences based on multiple factors for better sentence selection
        """
        # Get the word frequency distribution
        all_words = []
        for sentence in sentences:
            all_words.extend([word.lower() for word in sentence.split() 
                               if word.lower() not in self.stopwords.get(self.lang_code, set())])
        
        word_freq = Counter(all_words)
        max_freq = max(word_freq.values()) if word_freq else 1
        
        # Calculate normalized word frequency
        word_scores = {}
        for word, freq in word_freq.items():
            word_scores[word] = freq / max_freq
            
            # Boost important terms if they exist in our dictionary
            if word in self.important_terms.get(self.lang_code, {}):
                word_scores[word] *= self.important_terms[self.lang_code][word]
        
        # Score each sentence
        sentence_scores = {}
        
        for i, sentence in enumerate(sentences):
            words = [word.lower() for word in sentence.split() 
                     if word.lower() not in self.stopwords.get(self.lang_code, set())]
            
            if not words:
                sentence_scores[i] = 0
                continue
            
            # Base score from word importance
            score = sum(word_scores.get(word, 0) for word in words) / len(words)
            
            # Position weight (first and last sentences often important)
            position_weight = 1.0
            if i == 0:  # First sentence
                position_weight = 1.25
            elif i == len(sentences) - 1:  # Last sentence
                position_weight = 1.15
                
            # Apply position weight
            score *= position_weight
            
            # Store score
            sentence_scores[i] = score
        
        return sentence_scores
    
    def _select_key_sentences(self, sentences: List[str], 
                              scores: Dict[int, float], 
                              target_sentences: int = 3) -> List[int]:
        """Select the most important sentences based on scores and diversity"""
        # Validate inputs
        if not sentences:
            return []
        
        # Get top sentences while maintaining original order
        num_to_select = min(target_sentences, len(sentences))
        top_indices = sorted(scores.keys(), key=lambda i: scores[i], reverse=True)[:num_to_select]
        
        # Return indices in original document order
        return sorted(top_indices)
    
    def _compress_sentence(self, sentence: str, aggressive: bool = False) -> str:
        """
        Apply rule-based compression to remove less important words from sentences
        """
        words = sentence.split()
        
        # For short sentences, don't compress
        if len(words) <= 8:
            return sentence
        
        # Get stopwords for the language
        stopwords = self.stopwords.get(self.lang_code, set())
        
        # Words to keep
        filtered_words = []
        
        for i, word in enumerate(words):
            word_lower = word.lower()
            
            # Always keep first 2-3 words (often subject + verb)
            if i < 3:
                filtered_words.append(word)
                continue
            
            # Skip stopwords for aggressive compression
            if aggressive and word_lower in stopwords:
                continue
            
            # Keep words with special characters (often named entities)
            if any(c in word for c in '0123456789-_'):
                filtered_words.append(word)
                continue
            
            # Keep longer words which tend to be more significant
            if (self.lang_code == 'te' and len(word) > 5) or \
               (self.lang_code == 'hi' and len(word) > 4):
                filtered_words.append(word)
                continue
            
            # Keep important terms defined in our dictionary
            if word_lower in self.important_terms.get(self.lang_code, {}):
                filtered_words.append(word)
                continue
            
            # For moderate compression, keep more words
            if not aggressive or i % 2 == 0:
                filtered_words.append(word)
        
        # If we compressed too much, revert to a simpler approach
        if len(filtered_words) < len(words) // 3:
            if aggressive:
                # Keep first half for aggressive
                return ' '.join(words[:len(words)//2])
            else:
                # Keep most words for moderate compression
                return ' '.join([w for i, w in enumerate(words) if i < 3 or i % 3 != 1])
        
        return ' '.join(filtered_words)
    
    def _enhance_flow(self, sentences: List[str]) -> List[str]:
        """
        Enhance the flow between sentences using connectors
        """
        if not sentences or len(sentences) <= 1:
            return sentences
        
        # Get connectors for the language
        all_connectors = self.connectors.get(self.lang_code, {})
        default_connectors = all_connectors.get('additive', [])
        
        # Enhanced sentences
        enhanced_sentences = [sentences[0]]  # First sentence remains unchanged
        
        for i in range(1, len(sentences)):
            sentence = sentences[i]
            prev_sentence = sentences[i-1]
            
            # Determine connector type based on content and position
            connector_type = 'additive'  # Default connector type
            
            # Last sentence often summarizes
            if i == len(sentences) - 1:
                connector_type = 'summary'
            # Check for contrasting content
            elif any(word in sentence.lower() for word in ['కానీ', 'అయితే', 'लेकिन', 'परंतु']):
                connector_type = 'contrastive'
            # Check for causal relationships
            elif any(word in sentence.lower() for word in ['కాబట్టి', 'అందువలన', 'इसलिए', 'क्योंकि']):
                connector_type = 'causal'
            
            # Get connectors of the determined type
            connectors = all_connectors.get(connector_type, default_connectors)
            
            # Skip adding connector if sentence already starts with one
            if any(sentence.lower().startswith(conn.lower()) for conn in 
                   [c for connector_list in all_connectors.values() for c in connector_list]):
                enhanced_sentences.append(sentence)
                continue
            
            # Select a connector based on position
            connector = connectors[min(i-1, len(connectors)-1)] if connectors else ""
            
            # Add the connector and sentence
            if connector:
                enhanced_sentences.append(f"{connector}, {sentence}")
            else:
                enhanced_sentences.append(sentence)
        
        return enhanced_sentences
    
    def _enhance_final_summary(self, summary: str) -> str:
        """
        Apply final enhancements to make the summary more cohesive and complete
        """
        # Clean up double punctuation
        summary = re.sub(r'([.!?।॥])\s*([.!?।॥])', r'\1', summary)
        
        # Ensure consistent spacing
        summary = re.sub(r'\s+', ' ', summary)
        
        # Clean up spaces before punctuation
        summary = re.sub(r'\s+([,.!?:;।॥])', r'\1', summary)
        
        # Fix incorrect sentence boundaries
        if self.lang_code == 'te':
            # For Telugu - fix sentences ending with conjunctions
            summary = re.sub(r'(మరియు|కానీ|లేదా|అయితే)\.', r'\1', summary)
        elif self.lang_code == 'hi':
            # For Hindi - fix sentences ending with conjunctions
            summary = re.sub(r'(और|लेकिन|या|किंतु)\.', r'\1', summary)
        
        return summary.strip()
    
    def _generate_summary_structure(self, text: str, compression_ratio: float = 0.5) -> str:
        """
        Generate a structured summary using a combination of approaches:
        1. Smart sentence selection
        2. Sentence compression
        3. Flow enhancement with connectors
        """
        # Segment text into sentences
        sentences = self._segment_text(text)
        
        # For very short texts, return as is
        if len(sentences) <= 2:
            return text
        
        # Score sentences based on importance
        sentence_scores = self._score_sentences(sentences)
        
        # Calculate target number of sentences
        target_sentences = max(1, min(5, int(len(sentences) * compression_ratio + 0.5)))
        
        # Select key sentences
        selected_indices = self._select_key_sentences(
            sentences, sentence_scores, target_sentences
        )
        
        # Get selected sentences
        selected_sentences = [sentences[i] for i in selected_indices]
        
        # Apply compression to longer sentences
        compressed_sentences = []
        for sentence in selected_sentences:
            # Apply more aggressive compression to longer sentences
            if len(sentence.split()) > 15:
                compressed = self._compress_sentence(sentence, aggressive=True)
            elif len(sentence.split()) > 10:
                compressed = self._compress_sentence(sentence, aggressive=False)
            else:
                compressed = sentence  # No compression for short sentences
            
            compressed_sentences.append(compressed)
        
        # Enhance flow with appropriate connectors
        enhanced_sentences = self._enhance_flow(compressed_sentences)
        
        # Join sentences into summary
        summary = ' '.join(enhanced_sentences)
        
        # Apply final enhancements
        summary = self._enhance_final_summary(summary)
        
        return summary
    
    def summarize(self, text: str, compression_ratio: float = 0.5) -> str:
        """
        Generate a summary of the input text using our neural-guided approach
        
        Args:
            text: Text to summarize
            compression_ratio: Target ratio of summary size to original text
        
        Returns:
            A coherent, well-formed summary
        """
        if not text or len(text.strip()) == 0:
            return "Empty text provided."
        
        try:
            # Generate the summary
            summary = self._generate_summary_structure(text, compression_ratio)
            
            # Return the final summary
            return summary
            
        except Exception as e:
            logger.error(f"Error in summarization: {e}")
            # Fallback to simple extraction of first sentence
            sentences = self._segment_text(text)
            return sentences[0] if sentences else "Summarization failed."


