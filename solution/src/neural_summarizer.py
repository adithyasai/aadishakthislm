def generate_neural_summary(text: str, lang: str = 'te', 
                           model_dir: str = None, 
                           config_path: str = None,
                           compression_ratio: float = 0.5,
                           **kwargs) -> str:
    """
    Generate a neural-guided summary for the given text
    
    This function is the main entry point for generating summaries with the
    neural summarizer. It handles locating model files and configuration,
    and gracefully falls back to rule-based summarization if model loading fails.
    
    Args:
        text: Text to summarize
        lang: Language code ('te' for Telugu, 'hi' for Hindi)
        model_dir: Path to the model directory (optional, will use default if None)
        config_path: Path to the model config (optional, will use default if None)
        compression_ratio: Target ratio of summary to original text (0.0-1.0)
    
    Returns:
        A coherent summary of the text
    """
    try:
        # Get default paths if not provided
        if not model_dir or not config_path:
            base_dir = Path(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
            model_dir = model_dir or str(base_dir / "models" / "final_model")
            config_path = config_path or str(base_dir / "configs" / "model_config.json")
            
            # Verify paths exist
            if not Path(model_dir).exists():
                logger.warning(f"Default model directory not found: {model_dir}")
                logger.warning("Using rule-based summarization only")
                
            if not Path(config_path).exists():
                logger.warning(f"Default config path not found: {config_path}")
                logger.warning("Using rule-based summarization only")
        
        # Initialize the summarizer
        summarizer = NeuralSummarizer(
            model_path=model_dir,
            config_path=config_path,
            lang_code=lang
        )
        
        # Generate the summary
        summary = summarizer.summarize(text, compression_ratio)
        return summary
        
    except Exception as e:
        logger.error(f"Error in neural summarization: {e}")
        logger.error("Falling back to basic summarization")
        
        # Extremely simple fallback - just return the first 1-2 sentences
        sentences = re.split(r'(?<=[.!?।॥])\s+', text)
        if not sentences:
            return "Summarization failed."
        
        # Return first sentence for very short texts, or first two for longer ones
        if len(sentences) <= 3:
            return sentences[0]
        else:
            return ' '.join(sentences[:2])


