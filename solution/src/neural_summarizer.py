    def __init__(self, 
                 model_path: str, 
                 config_path: str, 
                 lang_code: str = 'te'):
        """
        Initialize the neural summarizer with a pretrained model
        
        Args:
            model_path: Path to the model directory containing the model files
            config_path: Path to the model config file
            lang_code: Language code ('te' for Telugu, 'hi' for Hindi)
            
        Raises:
            FileNotFoundError: If model files or config cannot be found
            RuntimeError: If there are issues loading the model
        """
        self.lang_code = lang_code
        self.model_loaded = False
        
        # Validate paths
        self._validate_paths(model_path, config_path)
        
        try:
            # Load tokenizer and model
            self.tokenizer = IndicTokenizer(config_path)
            self.config = IndicSLMConfig.from_pretrained(model_path)
            self.model = IndicSLM.from_pretrained(model_path, config=self.config)
            self.model.eval()  # Set to evaluation mode
            self.model_loaded = True
            logger.info(f"Model successfully loaded from {model_path}")
        except Exception as e:
            logger.warning(f"Error loading model: {e}. Falling back to rule-based approach only.")
            self.model = None
            self.tokenizer = None
            self.config = None
        
        # Define language-specific resources
        self._initialize_language_resources()
    
    def _validate_paths(self, model_path: str, config_path: str):
        """
        Validate that model and config paths exist
        
        Args:
            model_path: Path to the model directory
            config_path: Path to the config file
            
        Raises:
            FileNotFoundError: If paths don't exist
        """
        config_file = Path(config_path)
        model_dir = Path(model_path)
        
        if not config_file.exists():
            logger.warning(f"Config file not found: {config_path}")
        
        if not model_dir.exists():
            logger.warning(f"Model directory not found: {model_path}")
    
